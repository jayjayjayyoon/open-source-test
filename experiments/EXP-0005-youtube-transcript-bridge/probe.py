#!/usr/bin/env python3
"""EXP-0005: transcript-first YouTube reader, anonymous hosted-free providers.

Tested scope: one public watch/short URL, content evidence only. No media downloads,
cookies, account data, rate-limit evasion, public raw transcript, or paid API.
"""
import hashlib
import json
import re
import sys
from urllib.parse import parse_qs, urlparse

ID_RE = re.compile(r"^[A-Za-z0-9_-]{11}$")
PROVIDERS = ("apitoolcalls-ko", "youtubetotranscription-json", "transcriptfetch-mcp")
EXPIRED_ERROR = re.compile(r"quota|rate.limit|buy credits|login required|subscribe|no transcript|error:|failed to fetch", re.I)


def parse_video_id(url: str) -> str:
    if not url.startswith("https://") or len(url) > 800:
        raise ValueError("Only public HTTPS YouTube URLs are allowed")
    p = urlparse(url)
    host = (p.hostname or "").lower()
    if host in ("www.youtube.com", "youtube.com", "m.youtube.com") and p.path == "/watch":
        ids = parse_qs(p.query).get("v", [])
        vid = ids[0] if len(ids) == 1 else ""
    elif host in ("www.youtube.com", "youtube.com", "m.youtube.com") and p.path.startswith(("/shorts/", "/live/")):
        pieces = p.path.split("/")
        vid = pieces[2] if len(pieces) == 3 else ""
    elif host == "youtu.be":
        vid = p.path.removeprefix("/")
    else:
        raise ValueError("Unsupported host/path; use public YouTube watch, live, shorts, or youtu.be")
    if not ID_RE.fullmatch(vid):
        raise ValueError("Invalid YouTube video ID")
    return vid


def http_request(url, payload=None):
    import requests
    headers = {"Accept": "application/json, text/event-stream"}
    if payload is None:
        r = requests.get(url, timeout=20, headers=headers)
    else:
        r = requests.post(url, json=payload, timeout=20, headers=headers)
    if len(r.content) > 600_000:
        raise ValueError("Response size too large")
    r.raise_for_status()
    if "text/event-stream" in r.headers.get("content-type", ""):
        data = [line[5:].strip() for line in r.text.splitlines() if line.startswith("data:")]
        if not data:
            raise ValueError("No data in MCP event-stream")
        return json.loads(data[-1])
    return r.json()


def read_mcp(obj) -> tuple[str, dict]:
    if not isinstance(obj, dict) or obj.get("error"):
        raise ValueError("MCP error or non-object")
    r = obj.get("result") or {}
    if r.get("isError"):
        raise ValueError("MCP tool reported error")
    structured = r.get("structuredContent") or {}
    if isinstance(structured, dict):
        segments = structured.get("segments") or structured.get("transcript")
        if isinstance(segments, list):
            text = " ".join(s.get("text", "") for s in segments if isinstance(s, dict))
            if len(text) >= 400:
                return text, {"segment_count": len(segments), "title": structured.get("title")}
        for key in ("text", "transcript", "full_text"):
            if isinstance(structured.get(key), str) and len(structured[key]) >= 400:
                return structured[key], {"title": structured.get("title")}
    content = r.get("content") or []
    for part in content:
        val = part.get("text") if isinstance(part, dict) else None
        if not isinstance(val, str):
            continue
        try:
            parsed = json.loads(val)
            if isinstance(parsed, dict):
                for key in ("transcript", "text", "full_text"):
                    if isinstance(parsed.get(key), str) and len(parsed[key]) >= 400:
                        return parsed[key], {"title": parsed.get("title")}
        except ValueError:
            pass
        if len(val) >= 400 and not EXPIRED_ERROR.search(val[:350]):
            return val, {}
    raise ValueError("No usable caption body")


def provider_call(name: str, video: str) -> tuple[str, dict]:
    if name == "apitoolcalls-ko":
        obj = http_request("https://apitoolcalls.com/mcp", {"jsonrpc": "2.0", "id": 1,
            "method": "tools/call", "params": {"name": "get_transcript",
            "arguments": {"url": video, "lang": "ko"}}})
        return read_mcp(obj)
    if name == "youtubetotranscription-json":
        from urllib.parse import urlencode
        obj = http_request("https://youtubetotranscription.com/api/transcript?" + urlencode({"v": video}))
        if not isinstance(obj, dict) or obj.get("videoId") != video:
            raise ValueError("Video ID mismatch in provider result")
        val = obj.get("text")
        if not isinstance(val, str) or len(val) < 400:
            raise ValueError("No transcript from JSON provider")
        cues = obj.get("cues")
        return val, {"language": obj.get("language"), "is_auto_generated": obj.get("isAutoGenerated"),
                     "segment_count": len(cues) if isinstance(cues, list) else None,
                     "duration_seconds": obj.get("lengthSeconds"), "title": obj.get("title")}
    if name == "transcriptfetch-mcp":
        obj = http_request("https://transcriptfetch.com/mcp/try", {"jsonrpc": "2.0", "id": 1,
            "method": "tools/call", "params": {"name": "get_transcript",
            "arguments": {"video": video}}})
        return read_mcp(obj)
    raise ValueError("Unknown approved provider")


def evidence(text: str, name: str, video: str, meta: dict) -> dict:
    trimmed = re.sub(r"\s+", " ", text).strip()
    if len(trimmed) < 400 or EXPIRED_ERROR.search(trimmed[:200]):
        raise ValueError("Caption body too short or provider error")
    ko_count = sum("가" <= ch <= "힣" for ch in trimmed)
    ratio = round(ko_count / max(len(trimmed), 1), 3)
    ts_count = len(re.findall(r"\[\d{2}:\d{2}\]", text))
    # This is evidence from a hosted provider, NOT independently audio-verified.
    return {"status": "caption-candidate", "video_id": video, "provider": name,
            "language_observed": "ko" if ratio >= 0.15 else "non-ko-or-translation",
            "hangul_ratio": ratio, "characters": len(trimmed), "timestamp_markers": ts_count,
            "sha256": hashlib.sha256(trimmed.encode("utf-8")).hexdigest(),
            "metadata": meta, "note": "No raw transcript logged; audio not directly checked."}


def offline_self_test() -> None:
    assert parse_video_id("https://www.youtube.com/watch?v=qEVZ7AgB7zI") == "qEVZ7AgB7zI"
    assert parse_video_id("https://youtu.be/76js2AphU5g") == "76js2AphU5g"
    assert parse_video_id("https://www.youtube.com/watch?v=qEVZ7AgB7zI&list=LL") == "qEVZ7AgB7zI"
    assert parse_video_id("https://www.youtube.com/shorts/76js2AphU5g") == "76js2AphU5g"
    for invalid in ("http://www.youtube.com/watch?v=qEVZ7AgB7zI",
                    "https://example.com/watch?v=qEVZ7AgB7zI",
                    "https://www.youtube.com/watch?v=bad"):
        try:
            parse_video_id(invalid)
        except ValueError:
            continue
        raise AssertionError("Invalid URL accepted")
    e = evidence("안녕하세요 " * 80, "test", "qEVZ7AgB7zI", {})
    assert e["status"] == "caption-candidate" and e["language_observed"] == "ko"
    print("offline-check=passed (URL allowlist, caption evidence; no live site)", flush=True)


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "--self-test":
        offline_self_test()
        return
    if len(sys.argv) != 2:
        raise ValueError("Usage: probe.py PUBLIC_YOUTUBE_URL | --self-test")
    video = parse_video_id(sys.argv[1])
    errors = []
    first_non_ko = None
    for name in PROVIDERS:
        try:
            content, metadata = provider_call(name, video)
            result = evidence(content, name, video, metadata)
            print("PROVIDER_RESULT " + json.dumps(result, ensure_ascii=False), flush=True)
            if result["language_observed"] == "ko":
                print("SELECTED_RESULT " + json.dumps(result, ensure_ascii=False), flush=True)
                return
            if first_non_ko is None:
                first_non_ko = result
        except Exception as ex:
            msg = {"provider": name, "status": "failed", "error_type": type(ex).__name__,
                   "message": str(ex)[:140]}
            errors.append(msg)
            print("PROVIDER_RESULT " + json.dumps(msg, ensure_ascii=False), flush=True)
    if first_non_ko is not None:
        print("SELECTED_RESULT " + json.dumps(first_non_ko, ensure_ascii=False), flush=True)
        print("WARN: Korean captions unavailable in this run. Non-Korean content is not claimed to be original audio.", flush=True)
        return
    raise RuntimeError("No caption provider succeeded for this public video; see individual errors")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, RuntimeError) as exc:
        print(f"PROBE_FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
        raise SystemExit(1)
